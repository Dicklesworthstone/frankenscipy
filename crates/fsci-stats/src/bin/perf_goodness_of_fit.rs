//! Whole-job head-to-head for `goodness_of_fit` against `scipy.stats.goodness_of_fit`.
//!
//! Both arms do the SAME job: fit a normal to the data, compute the statistic,
//! then build a Monte Carlo null of `n_mc` resamples, REFITTING each one. The
//! p-value is printed so the two arms can be checked to agree before any timing
//! is believed.
//!
//! Usage: perf_goodness_of_fit <n_mc> <seed>
use fsci_stats::{GofOutcome, GofStatistic, Normal, goodness_of_fit};

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let n_mc: usize = args.get(1).and_then(|s| s.parse().ok()).unwrap_or(999);
    let seed: u64 = args.get(2).and_then(|s| s.parse().ok()).unwrap_or(20260819);

    // The same 50-point sample the python arm uses, generated by a fixed rule so
    // neither arm can be handed different data.
    let data: Vec<f64> = (0..50)
        .map(|i| {
            let t = (i as f64 + 0.5) / 50.0;
            // Inverse-normal-ish deterministic spread; exact values do not matter,
            // only that both arms see the identical bytes.
            (t - 0.5) * 6.0 + ((i * 7919) % 97) as f64 * 0.01
        })
        .collect();

    let t0 = std::time::Instant::now();
    let res: GofOutcome<Normal> =
        goodness_of_fit(&data, GofStatistic::AndersonDarling, n_mc, seed).expect("fit");
    let dt = t0.elapsed();

    println!(
        "arm=fsci n_mc={n_mc} statistic={:.12e} pvalue={:.6} failed_fits={} secs={:.6}",
        res.statistic,
        res.pvalue,
        res.failed_fits,
        dt.as_secs_f64()
    );
}
